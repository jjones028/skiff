package skiff.project

import skiff.SkiffException
import skiff.maven.ModuleId
import java.nio.file.Files
import java.nio.file.Path
import kotlin.test.AfterTest
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFailsWith
import kotlin.test.assertNull
import kotlin.test.assertTrue

class LockfileTest {
    private val dir: Path = Files.createTempDirectory("skiff-lock-test")
    private val file = dir.resolve(Lockfile.FILE_NAME)

    @AfterTest
    fun cleanUp() {
        dir.toFile().deleteRecursively()
    }

    private val lockfile = Lockfile(
        fingerprint = "abc123",
        packages = listOf(
            LockedPackage(ModuleId("g", "a"), "1.0", "f".repeat(64), listOf(ModuleId("g", "b"), ModuleId("h", "c"))),
            LockedPackage(ModuleId("g", "b"), "2.0-rc1", "0".repeat(64), emptyList()),
            LockedPackage(ModuleId("g", "bom"), "3", null, emptyList()),
        ),
    )

    @Test
    fun roundTripsThroughTheFile() {
        Files.writeString(file, lockfile.render())
        assertEquals(lockfile, Lockfile.read(file))
    }

    @Test
    fun renderingIsDeterministicAndMarkedAsGenerated() {
        val text = lockfile.render()
        assertEquals(text, lockfile.copy().render())
        assertTrue(text.startsWith("# This file is generated by skiff."))
        assertTrue("fingerprint = \"abc123\"" in text)
    }

    @Test
    fun omitsShaForJarlessPackagesAndEmptyDependencyLists() {
        val text = lockfile.copy(packages = listOf(lockfile.packages[2])).render()
        assertTrue("sha256" !in text)
        assertTrue("dependencies" !in text)
    }

    @Test
    fun readReturnsNullWhenTheFileIsMissing() {
        assertNull(Lockfile.read(file))
    }

    @Test
    fun readsAnEmptyLockfile() {
        Files.writeString(file, Lockfile("fp", emptyList()).render())
        assertEquals(Lockfile("fp", emptyList()), Lockfile.read(file))
    }

    @Test
    fun rejectsUnsupportedFormatVersions() {
        Files.writeString(file, "version = 99\nfingerprint = \"x\"\n")
        val error = assertFailsWith<SkiffException> { Lockfile.read(file) }
        assertTrue("unsupported lockfile version" in error.message!!, error.message)
    }

    @Test
    fun jarPathFollowsTheMavenLayout() {
        assertEquals("com/squareup/okhttp3/okhttp/4.12.0/okhttp-4.12.0.jar", LockedPackage(ModuleId("com.squareup.okhttp3", "okhttp"), "4.12.0", null, emptyList()).jarPath)
    }
}
