package skiff.project

import skiff.SkiffException
import skiff.maven.ModuleId
import skiff.toml.Toml
import java.nio.file.Files
import java.nio.file.Path

/**
 * `Skiff.lock`: the exact versions and checksums of every resolved package.
 * [fingerprint] is the manifest's [Manifest.resolutionFingerprint] at the time of resolution.
 */
data class Lockfile(val fingerprint: String, val packages: List<LockedPackage>) {
    fun render(): String = buildString {
        appendLine("# This file is generated by skiff. Do not edit it by hand.")
        appendLine("version = $FORMAT_VERSION")
        appendLine("fingerprint = ${Toml.quote(fingerprint)}")
        for (pkg in packages) {
            appendLine()
            appendLine("[[package]]")
            appendLine("id = ${Toml.quote(pkg.module.toString())}")
            appendLine("version = ${Toml.quote(pkg.version)}")
            pkg.sha256?.let { appendLine("sha256 = ${Toml.quote(it)}") }
            if (pkg.dependencies.isNotEmpty()) {
                appendLine("dependencies = [")
                pkg.dependencies.forEach { appendLine("    ${Toml.quote(it.toString())},") }
                appendLine("]")
            }
        }
    }

    companion object {
        const val FILE_NAME = "Skiff.lock"
        private const val FORMAT_VERSION = 1L

        fun read(file: Path): Lockfile? {
            if (!Files.isRegularFile(file)) return null
            val toml = Toml.parse(Files.readString(file), FILE_NAME)
            if (toml["version"] != FORMAT_VERSION) throw SkiffException("$FILE_NAME: unsupported lockfile version ${toml["version"]}")
            val packages = (toml["package"] as? List<*>).orEmpty().map { entry ->
                val table = entry as Map<*, *>
                LockedPackage(
                    module = ModuleId.parse(table["id"] as String),
                    version = table["version"] as String,
                    sha256 = table["sha256"] as String?,
                    dependencies = (table["dependencies"] as? List<*>).orEmpty().map { ModuleId.parse(it as String) },
                )
            }
            return Lockfile(toml["fingerprint"] as? String ?: "", packages)
        }
    }
}
